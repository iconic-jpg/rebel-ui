import { jsx as _jsx, jsxs as _jsxs, Fragment as _Fragment } from "react/jsx-runtime";
import { useEffect, useState } from "react";
import { useNavigate } from "react-router-dom";
import { AUTH_API } from "../Auth/authApi.js";

const REDIRECT_URI = `${window.location.origin}/auth/google/callback`;

const styles = `
  @import url('https://fonts.googleapis.com/css2?family=Share+Tech+Mono&display=swap');
  @keyframes blink {
    0%, 100% { opacity: 0.4; }
    50% { opacity: 1; }
  }
  .cb-root {
    min-height: 100vh;
    background: #020b18;
    display: flex;
    flex-direction: column;
    align-items: center;
    justify-content: center;
    font-family: 'Share Tech Mono', monospace;
    gap: 16px;
  }
  .cb-text {
    font-size: 10px;
    letter-spacing: 4px;
    color: rgba(0,200,255,.35);
    animation: blink 1.2s ease-in-out infinite;
  }
  .cb-error {
    font-size: 10px;
    letter-spacing: 2px;
    color: rgba(255,80,80,.8);
    padding: 10px 16px;
    border-left: 2px solid rgba(255,80,80,.4);
    background: rgba(255,80,80,.04);
    max-width: 420px;
    text-align: center;
  }
  .cb-back {
    font-size: 9px;
    letter-spacing: 3px;
    color: rgba(0,200,255,.4);
    text-decoration: none;
    border-bottom: 1px solid rgba(0,200,255,.2);
    padding-bottom: 2px;
    transition: color 0.2s;
  }
  .cb-back:hover { color: #00c8ff; }
`;

export default function GoogleCallback() {
    const navigate = useNavigate();
    const [error, setError] = useState("");

    useEffect(() => {
        let cancelled = false;

        async function completeGoogleLogin() {
            const params = new URLSearchParams(window.location.search);
            const code = params.get("code");
            const state = params.get("state");
            const googleError = params.get("error");
            const savedState = sessionStorage.getItem("google_oauth_state");

            // Remove the authorization code from the visible URL.
            window.history.replaceState({}, "", "/auth/google/callback");

            if (googleError) {
                setError("Google sign-in was cancelled or denied.");
                return;
            }

            if (!code) {
                setError("No authorisation code received from Google.");
                return;
            }

            // Require the state generated by the login/signup flow.
            if (!savedState || !state || state !== savedState) {
                sessionStorage.removeItem("google_oauth_state");
                setError("OAuth state validation failed. Please try signing in again.");
                return;
            }

            sessionStorage.removeItem("google_oauth_state");

            try {
                // Exchange Google's authorization code through Django.
                const response = await fetch(`${AUTH_API}/api/auth/google/`, {
                    method: "POST",
                    headers: {
                        "Content-Type": "application/json",
                        "Accept": "application/json",
                    },
                    body: JSON.stringify({
                        code,
                        redirect_uri: REDIRECT_URI,
                    }),
                });

                const data = await response.json().catch(() => ({}));

                if (!response.ok) {
                    throw new Error(
                        data.detail ||
                        data.error ||
                        data.message ||
                        `Google authentication failed (${response.status}).`
                    );
                }

                // Django must return SimpleJWT access and refresh tokens.
                if (
                    typeof data.access !== "string" ||
                    !data.access ||
                    typeof data.refresh !== "string" ||
                    !data.refresh
                ) {
                    throw new Error(
                        "Django authentication did not return valid access and refresh tokens."
                    );
                }

                if (cancelled) return;

                // Use the same storage convention as email/password login.
                localStorage.setItem("access", data.access);
                localStorage.setItem("refresh", data.refresh);

                navigate("/splash", { replace: true });
            } catch (err) {
                if (!cancelled) {
                    setError(
                        err.message || "Could not complete Google authentication."
                    );
                }
            }
        }

        completeGoogleLogin();

        return () => {
            cancelled = true;
        };
    }, [navigate]);

    return _jsxs(_Fragment, {
        children: [
            _jsx("style", { children: styles }),
            _jsx("div", {
                className: "cb-root",
                children: error
                    ? _jsxs(_Fragment, {
                        children: [
                            _jsx("div", {
                                className: "cb-error",
                                children: error,
                            }),
                            _jsx("a", {
                                href: "/login",
                                className: "cb-back",
                                children: "← back to login",
                            }),
                        ],
                    })
                    : _jsx("span", {
                        className: "cb-text",
                        children: "// authenticating with django...",
                    }),
            }),
        ],
    });
}
